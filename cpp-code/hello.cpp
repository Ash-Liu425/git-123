#include <iostream>
#include <string>

int main() {
    std::string name = "World";
    std::cout << "Hello, " << name << "!" << std::endl;

    // Simple demonstration of a loop and a function call
    for (int i = 1; i <= 3; ++i) {
        std::cout << "Iteration " << i << std::endl;
    }

    return 0;
}
